#!/usr/bin/env python3
"""Generate the *serving* tables of benchmarks/RESULTS.md.

Sources: suite.json + receipts/pins/*.json (ferrox-server vs llama-server
over HTTP). The *engine* table in the same file — `ferrox bench` vs
`llama-bench`, no HTTP in the loop — is owned by `ferrox bench --render`,
which splices itself between the ENGINE_BEGIN/ENGINE_END markers this
script emits. Two generators, one file, disjoint regions: whichever runs
second must not clobber the other's work.

Do not hand-edit RESULTS.md — re-run this script (or run_suite.py), and
`ferrox bench --render` for the engine table.
"""

from __future__ import annotations

import json
from pathlib import Path

# Owned by `ferrox bench --render`; this script only emits the markers and
# a placeholder, never the contents.
ENGINE_BEGIN = "<!-- BEGIN ENGINE TABLE (generated by `ferrox bench --render`) -->\n"
ENGINE_END = "<!-- END ENGINE TABLE -->\n"

BENCH = Path(__file__).resolve().parent
SUITE_PATH = BENCH / "suite.json"
PINS = BENCH / "receipts" / "pins"
ENGINE = BENCH / "receipts" / "engine"
OUT = BENCH / "RESULTS.md"


def load_json(path: Path) -> dict | None:
    if not path.is_file():
        return None
    return json.loads(path.read_text())


def fmt_num(x, sd=None) -> str:
    if x is None:
        return "—"
    if isinstance(sd, (int, float)):
        return f"**{x:.2f}** ±{sd:.1f}"
    return f"**{x:.2f}**"


def stddev(row: dict | None):
    if not row or row.get("error"):
        return None
    v = row.get("predicted_stddev")
    return v if isinstance(v, (int, float)) else None


def pred(row: dict | None):
    if not row or row.get("error"):
        return None
    v = row.get("predicted_per_second")
    return v if isinstance(v, (int, float)) else None


def load_s(row: dict | None):
    """Prefer comparable `startup_s` (wall − decode); fall back to engine load."""
    if not row or row.get("error"):
        return None
    for key in ("startup_s", "load_s"):
        v = row.get(key)
        if isinstance(v, (int, float)):
            return v
    return None


def load_sd(row: dict | None):
    if not row or row.get("error"):
        return None
    for key in ("startup_stddev", "load_stddev"):
        v = row.get(key)
        if isinstance(v, (int, float)):
            return v
    return None


def cli_pin_trustworthy(pin: dict) -> bool:
    """Reject CLI pins known to have used llama-cli or mismatched templates."""
    llama = pin.get("llama") or {}
    if llama.get("error"):
        return False
    prefix = str(llama.get("prefix") or "")
    log = str(llama.get("log_tail") or "")
    if "not supported by llama-cli" in prefix or "not supported by llama-cli" in log:
        return False
    if "please use llama-completion" in prefix or "please use llama-completion" in log:
        return False
    # Stale 256-tok / 1-rep server-shaped CLI leftovers
    if pin.get("max_tokens") not in (None, 512) and pin.get("max_tokens", 512) < 512:
        return False
    return True


def fmt_load(x, sd=None) -> str:
    """Format load/startup seconds (keep ms precision for sub-second loads)."""
    if x is None:
        return "—"
    if isinstance(sd, (int, float)):
        return f"**{x:.3f}** ±{sd:.3f}"
    return f"**{x:.3f}**"


def gap_ratio(fp, lp) -> float | None:
    if fp and lp and fp > 0:
        return lp / fp
    return None


# Near-parity band: tok/s jitter of a few percent is not a meaningful win/loss.
# ~1.03–1.04× is treated as parity (⚪), not 🔴 llama.
PARITY_BAND = 0.05


def color_gap(g: float | None, *, lower_is_better: bool = False) -> str:
    """Gap cell for GitHub markdown (no inline CSS — GH strips it).

    Convention: gap < 1 → ferrox better. Uses emoji + bold text so the
    signal survives GitHub Flavored Markdown. Within ``PARITY_BAND`` of
    1.0 → ⚪ near-parity (not a loss).
    """
    del lower_is_better  # ratios are pre-normalized to "<1 = ferrox better"
    if g is None:
        return "—"
    if abs(g - 1.0) < PARITY_BAND:
        if abs(g - 1.0) < 0.015:
            return "⚪ **1.00×**"
        return f"⚪ **~{g:.2f}×**"
    if g < 1.0:
        return f"🟢 **~{g:.2f}×**"
    return f"🔴 **~{g:.2f}×**"


def gap_str(fp, lp) -> str:
    return color_gap(gap_ratio(fp, lp))


def winner_str(fp, lp) -> str:
    """Who is faster on predicted tok/s (same near-parity band as gap_str)."""
    g = gap_ratio(fp, lp)
    if g is None:
        return "—"
    if abs(g - 1.0) < PARITY_BAND:
        return "⚪ parity"
    if g < 1.0:
        return "🟢 **ferrox**"
    return "🔴 **llama**"


def status_cell(pin: dict | None, expect: str) -> str:
    if pin is None:
        return "no pin"
    st = pin.get("status", "ok")
    if st in ("missing", "refuse", "error", "weak"):
        return st
    if expect == "weak":
        return "weak"
    return "ok"


def main() -> None:
    suite = json.loads(SUITE_PATH.read_text())
    pins: dict[tuple[str, str], dict] = {}
    cli_pins: dict[tuple[str, str], dict] = {}
    orphan_pin_files: list[str] = []
    if PINS.is_dir():
        for path in PINS.glob("*.json"):
            data = load_json(path)
            if not data:
                orphan_pin_files.append(path.name)
                continue
            key = (data.get("id"), data.get("backend"))
            if key[0] and key[1]:
                if data.get("mode") == "cli":
                    cli_pins[key] = data
                else:
                    pins[key] = data
            else:
                orphan_pin_files.append(path.name)

    # Fail closed on unreadable / schema-invalid pin JSON. Suite entries may
    # lack pin files (shown as "no pin"); never emit markdown links to missing
    # files. Extra on-disk pins (e.g. future CUDA) are fine if they parse.
    if orphan_pin_files:
        raise SystemExit(
            "render_results.py validation failed — unreadable or schema-invalid "
            f"pins: {', '.join(orphan_pin_files)}"
        )

    # A pin is "stale" if it was measured with a forced thread count, or
    # predates the `threads_forced` key entirely (all of those used -t 10).
    # Deriving the banner from the pins means it disappears by itself as they
    # are re-pinned, rather than becoming another stale claim in a file whose
    # whole problem was stale claims.
    ok_pins = [v for v in pins.values() if v.get("status") == "ok"]
    stale_pins = [v for v in ok_pins if v.get("threads_forced", "absent") is not None]
    if stale_pins:
        stale_banner = (
            "> [!WARNING]\n"
            f"> **{len(stale_pins)} of {len(ok_pins)} serving pins were measured with a\n"
            "> forced thread count** (the harness used to pin both engines to `-t 10`).\n"
            "> On this host llama.cpp defaults to 6 performance cores and loses 2-4x\n"
            "> when pushed above them, so those rows handicap llama and flatter ferrox.\n"
            "> Re-pin with `run_suite.py`, which no longer forces `-t`. The engine\n"
            "> table is freshly measured.\n"
            "\n"
        )
    else:
        stale_banner = ""

    # Headline the *engine* number when one exists. Prefer Llama-3.2-3B
    # Metal decode as the suite flagship (Llama-3.1 dropped once 3.2 landed).
    engine_flag = load_json(ENGINE / "llama32_3b_q4km_metal.json")
    tg_flag = None
    if engine_flag:
        tg_flag = next(
            (
                t
                for t in engine_flag.get("tests", [])
                if str(t.get("test", "")).startswith("tg")
            ),
            None,
        )
    metal_flag = pins.get(("llama32_3b_q4km", "metal"))
    if tg_flag and tg_flag.get("ferrox_tps") and tg_flag.get("llama_tps"):
        fp = tg_flag["ferrox_tps"]
        lp = tg_flag["llama_tps"]
        north = (
            f"**Llama-3.2-3B Metal decode (engine):** {fmt_num(fp)} vs llama {fmt_num(lp)} "
            f"{tg_flag.get('test', 'tg')} ({gap_str(fp, lp)}) — "
            "[`engine/llama32_3b_q4km_metal.json`]"
            "(receipts/engine/llama32_3b_q4km_metal.json). "
            "Prefill is farther behind; see the engine table.\n"
        )
    elif metal_flag and pred(metal_flag.get("ferrox")) and pred(metal_flag.get("llama")):
        fp = pred(metal_flag["ferrox"])
        lp = pred(metal_flag["llama"])
        north = (
            f"**Llama-3.2-3B Metal pin (serving):** {fmt_num(fp)} vs llama "
            f"{fmt_num(lp)} pred ({gap_str(fp, lp)}) — "
            f"[`pins/llama32_3b_q4km_metal.json`](receipts/pins/llama32_3b_q4km_metal.json).\n"
        )
    else:
        north = "**Llama-3.2-3B Metal pin:** not yet paired in `receipts/pins/`.\n"

    lines: list[str] = [
        "# Results vs llama.cpp\n",
        "\n",
        f"Host B = Apple M2 Pro (6 performance + 4 efficiency cores). "
        f"Thread counts are not forced — each engine picks its own default. "
        f"Greedy chat, warm, then "
        f"`max_tokens={suite.get('max_tokens', 512)}` × {suite.get('reps', 3)} reps "
        f"(median ± stddev) unless noted. Prefer **predicted** tok/s.\n",
        "\n",
        "Suite: [`suite.json`](suite.json) (shared). Runners: `ferrox bench --suite` "
        "(engine) and [`run_suite.py`](run_suite.py) (serving). "
        "Pins: [`receipts/pins/`](receipts/pins/). "
        "**This file is generated**: serving tables by "
        "[`render_results.py`](render_results.py), the engine table by "
        "`ferrox bench --render`. Do not hand-edit.\n",
        "\n",
        "**Gap** = `llama_pred / ferrox_pred` (&lt;1 ferrox faster; &gt;1 ferrox slower). "
        "**Winner** = faster engine on predicted tok/s "
        f"(near-parity within ~{PARITY_BAND * 100:.0f}%).\n",
        "\n",
        "**North star:** ≥ llama.cpp same host/GGUF/backend.\n",
        "\n",
        stale_banner,
        north,
        "\n",
        "One pin per `(model_id, backend)`. Re-run overwrites the pin. "
        "Gap only when both engines succeed.\n",
        "\n",
        "**Gap colors (GitHub-safe):** 🟢 ferrox better; "
        f"⚪ near-parity (within ~{PARITY_BAND * 100:.0f}%); "
        "🔴 ferrox meaningfully slower.\n",
        "\n",
        "Keep off (regressions): legacy GQA NSG=4, sequential GREEDY argmax, "
        "float4 elem, early Multi-CB. `FERROX_METAL_FA_VEC=0` → ~25.5 pred.\n",
        "\n",
        ENGINE_BEGIN,
        "\n",
        "_No engine receipts rendered yet — run `ferrox bench --suite`._\n",
        "\n",
        ENGINE_END,
        "\n",
        "\n",
        "## Serving (`ferrox-server` vs `llama-server`)\n",
        "\n",
        "Chat over HTTP: template, tokenizer, sampler and SSE are all in the\n"
        "loop. The prompt is ~30 tokens, so `prompt_per_second` here is noise —\n"
        "read prefill off the engine table above.\n",
        "\n",
        "Rows are grouped by backend (Metal → CUDA → CPU), then **worst gap\n"
        "first** within each group. Regenerate with `python3 benchmarks/render_results.py`.\n",
        "\n",
    ]

    backend_ord = {"metal": 0, "cuda": 1, "cpu": 2}

    def serving_row(entry: dict, backend: str) -> dict:
        mid = entry["id"]
        name = entry["name"]
        expect = entry.get("expect", "ok")
        pin = pins.get((mid, backend))
        fp = pred(pin.get("ferrox") if pin else None)
        lp = pred(pin.get("llama") if pin else None)
        fsd = stddev(pin.get("ferrox") if pin else None)
        lsd = stddev(pin.get("llama") if pin else None)
        st = status_cell(pin, expect)
        if st == "refuse":
            fcell = "refused"
        elif st == "missing":
            fcell = "—"
            lp = None
        elif fp is not None:
            fcell = fmt_num(fp, fsd)
        else:
            fcell = "—"
        lcell = fmt_num(lp, lsd) if lp is not None else "—"
        if backend == "cpu" and lp is not None:
            lcell = f"{lcell} (−ngl 0)"
        pin_name = f"{mid}_{backend}.json"
        link = (
            f"[`{mid}_{backend}`](receipts/pins/{pin_name})"
            if pin and (PINS / pin_name).is_file()
            else "—"
        )
        star = "\\*" if expect == "weak" else ""
        g = gap_ratio(fp, lp)
        return {
            "backend": backend,
            "gap": g if g is not None else -1.0,
            "line": (
                f"| {name}{star} | {fcell} | {lcell} | "
                f"{gap_str(fp, lp)} | {winner_str(fp, lp)} | {st} | {link} |\n"
            ),
            "summary": (name, backend, g, st),
        }

    serving_rows: list[dict] = []
    for entry in suite["models"]:
        for backend in entry["backends"]:
            serving_rows.append(serving_row(entry, backend))

    serving_rows.sort(
        key=lambda r: (
            backend_ord.get(r["backend"], 9),
            # Finite gaps first, worst first; missing/error (gap=-1) last.
            r["gap"] < 0,
            -(r["gap"] if r["gap"] >= 0 else 0.0),
            r["line"],
        )
    )

    worst_srv = [
        r
        for r in serving_rows
        if isinstance(r["gap"], float) and r["gap"] > 1.05
    ]
    worst_srv.sort(key=lambda r: -r["gap"])
    if worst_srv:
        lines.append("**Largest serving decode gaps (gap > 1.05×):**\n\n")
        for r in worst_srv[:8]:
            name, backend, g, _st = r["summary"]
            lines.append(f"- `{name}` / {backend}: {color_gap(g)}\n")
        lines.append("\n")

    def emit_serving_section(title: str, backend: str) -> None:
        rows = [r for r in serving_rows if r["backend"] == backend]
        if not rows:
            return
        lines.append(f"### {title}\n\n")
        lines.append(
            "| Model | ferrox pred (tok/s) | llama pred (tok/s) | Gap | Winner | Status | Pin |\n"
        )
        lines.append("|---|---|---|---|---|---|---|\n")
        for r in rows:
            lines.append(r["line"])
        lines.append("\n")

    emit_serving_section("Metal", "metal")
    emit_serving_section("CUDA", "cuda")
    emit_serving_section("CPU", "cpu")
    other_backends = sorted(
        {r["backend"] for r in serving_rows if r["backend"] not in backend_ord}
    )
    for b in other_backends:
        emit_serving_section(b, b)

    for e in suite["models"]:
        if e.get("expect") == "weak":
            lines.append(f"\\*weak — {e['name']}: {e.get('notes', 'see suite.json')}\n")
    miss_ids = sorted(
        {
            e["id"]
            for e in suite["models"]
            for b in e["backends"]
            if (pins.get((e["id"], b)) or {}).get("status") == "missing"
        }
    )
    if miss_ids:
        lines.append(
            f"Missing GGUF (no tok/s): {', '.join(f'`{i}`' for i in miss_ids)}. "
            "Place the files at their configured `models/` paths.\n"
        )

    if cli_pins:
        lines.append(
            "\n## CLI completion (`llama-completion` vs `ferrox run`)\n\n"
            "> [!NOTE]\n"
            "> Superseded for throughput by the engine table — use `ferrox bench`.\n"
            "> These pins disagree with the fair-chat ones (SmolLM2 metal: 80.71\n"
            "> here vs 282.29 there, same model and backend), and they were all\n"
            "> measured with a forced `-t 10` that the serving pins above no\n"
            "> longer use, so read this table for **process startup cost**, not\n"
            "> engine speed.\n\n"
            "One-shot `-p … -n N --ignore-eos -c 4096` with the **same capitals "
            "prompt + chat template** as fair-chat server (ferrox wraps via GGUF "
            "template; llama `-cnv --jinja`). Fresh process per rep, interleaved "
            "(llama then ferrox each rep). Requires `llama-completion` (not "
            "`llama-cli`). Engines' own stderr timings; **pred** tok/s excludes "
            "model load. **startup** = wall − decode (comparable process overhead); "
            "falls back to engine-reported load if startup missing. "
            "**Startup gap** = `ferrox / llama` (&lt;1 ferrox better).\n"
            "Pins that used `llama-cli` or rejected options are omitted.\n\n"
            "| Model | Backend | ferrox pred | llama pred | Gap | "
            "ferrox startup (s) | llama startup (s) | Startup gap | Pin |\n"
            "|---|---|---|---|---|---|---|---|---|\n"
        )
        for entry in suite["models"]:
            mid = entry["id"]
            for backend in entry["backends"]:
                pin = cli_pins.get((mid, backend))
                if not pin or pin.get("status") == "missing":
                    continue
                if not cli_pin_trustworthy(pin):
                    continue
                fp = pred(pin.get("ferrox"))
                lp = pred(pin.get("llama"))
                fsd = stddev(pin.get("ferrox"))
                lsd = stddev(pin.get("llama"))
                fl = load_s(pin.get("ferrox"))
                ll = load_s(pin.get("llama"))
                flsd = load_sd(pin.get("ferrox"))
                llsd = load_sd(pin.get("llama"))
                ferr = (pin.get("ferrox") or {}).get("error")
                fcell = "error" if ferr else fmt_num(fp, fsd)
                lcell = fmt_num(lp, lsd) if lp is not None else "—"
                load_gap = "—"
                if fl and ll and ll > 0:
                    load_gap = color_gap(fl / ll)
                lines.append(
                    f"| {entry['name']} | {backend} | {fcell} | {lcell} | "
                    f"{gap_str(fp, lp)} | {fmt_load(fl, flsd)} | {fmt_load(ll, llsd)} | "
                    f"{load_gap} | "
                    f"[`{mid}_{backend}_cli`](receipts/pins/{mid}_{backend}_cli.json) |\n"
                )

    lines.append("\n## Open\n\n")
    lines.append(
        "1. **Prefill gap narrowed hard (2026-08-10).** Dense Metal with "
        "QKV bias / QK-norm rides the fused prefill stack (`AttnExtras`); "
        "Qwen2.5 / Qwen3 / Gemma-3 metal pp512 ~1.2\u20132.1\u00d7. Phi-4 metal "
        "pp512 ~1.3\u00d7. OLMoE metal residual is gather\u2192`mul_mm_sg`\u2192"
        "scatter vs fused `kernel_mul_mm_id`. See `docs/ROADMAP.md`.\n"
        "2. **Metal decode is healthy** on many dense models (engine tg often "
        "\u22641\u00d7 with answer parity).\n"
        "3. **CPU decode stays behind** (~1.3\u20132.6\u00d7): lower per-thread GEMV + "
        "rayon fork-join vs llama persistent pool. i8mm SMMLA still open.\n"
        "4. CUDA — no in-tree pin; skipped on darwin via `--fit-host`.\n"
        "5. Gemma-4-E2B: SPM-style `gemma4` BPE + `<|turn>` chat wrap landed "
        "(2026-08-10). Fair-chat pin should measure ferrox; Homebrew llama may "
        "still lack `gemma4` arch (llama column \u2014 / error).\n"
        "6. Continuous-batching multi-request receipt "
        "(`cb_throughput.py` exists; not yet in this ledger).\n"
        "7. DS4 / GLM / MLA MoE real-checkpoint e2e when feasible. Mixtral "
        "skipped by `--fit-host` on Host B.\n"
        "8. Run-to-run spread on this host is ~20%; claims tighter than that "
        "need interleaved A/B (still sequential per engine).\n"
    )

    OUT.write_text("".join(lines))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
